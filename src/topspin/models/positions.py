"""Positions and cash ledger with explicit realized / unrealized / settled accounting."""

from __future__ import annotations

from decimal import Decimal

from pydantic import BaseModel, Field

from topspin.models.market import ONE, ZERO
from topspin.models.orders import Fill, OrderIntent


class Position(BaseModel):
    market_slug: str
    match_key: str
    side: str  # "YES" or "NO"
    qty: Decimal = ZERO
    # Remaining cost of open contracts in held-side price terms, *including* entry fees.
    cost_basis: Decimal = ZERO
    realized_pnl: Decimal = ZERO  # net of all fees on the closed portion
    fees_paid: Decimal = ZERO
    opened_local_ts_ns: int = 0
    entry_count: int = 0
    last_exit_local_ts_ns: int | None = None
    settled: bool = False
    settled_pnl: Decimal = ZERO

    @property
    def avg_cost(self) -> Decimal:
        return self.cost_basis / self.qty if self.qty > 0 else ZERO

    @property
    def max_settlement_loss(self) -> Decimal:
        """Loss if the held side settles at zero, including fees already paid."""
        return self.cost_basis

    def apply_fill(self, fill: Fill) -> Decimal:
        """Apply a fill; return the realized P&L generated by it (zero for entries)."""
        if fill.intent.holding != self.side:
            raise ValueError(f"fill side {fill.intent.holding} != position side {self.side}")
        px = fill.intent.side_price(fill.price)
        self.fees_paid += fill.fee
        if fill.intent.opens:
            if self.qty == 0:
                self.opened_local_ts_ns = fill.local_ts_ns
                self.entry_count += 1
            self.qty += fill.qty
            self.cost_basis += px * fill.qty + fill.fee
            return ZERO
        if fill.qty > self.qty:
            raise ValueError(f"closing {fill.qty} exceeds open qty {self.qty}")
        released = self.avg_cost * fill.qty
        pnl = px * fill.qty - fill.fee - released
        self.cost_basis -= released
        self.qty -= fill.qty
        self.realized_pnl += pnl
        if self.qty == 0:
            self.cost_basis = ZERO
            self.last_exit_local_ts_ns = fill.local_ts_ns
        return pnl

    def settle(self, yes_settlement_price: Decimal) -> Decimal:
        """Settle remaining contracts at the YES settlement price (1, 0, or an LFMP)."""
        payout_per = yes_settlement_price if self.side == "YES" else ONE - yes_settlement_price
        pnl = payout_per * self.qty - self.cost_basis
        self.settled_pnl += pnl
        self.realized_pnl += pnl
        self.qty = ZERO
        self.cost_basis = ZERO
        self.settled = True
        return pnl


class Ledger(BaseModel):
    """Cash + positions. Cash moves only on fills and settlements."""

    starting_cash: Decimal
    cash: Decimal
    positions: dict[str, Position] = Field(default_factory=dict)
    total_fees: Decimal = ZERO
    realized_pnl: Decimal = ZERO
    settled_pnl: Decimal = ZERO
    seen_fill_ids: set[str] = Field(default_factory=set)

    def position(self, market_slug: str) -> Position | None:
        return self.positions.get(market_slug)

    def apply_fill(self, fill: Fill) -> Decimal:
        if fill.fill_id in self.seen_fill_ids:
            return ZERO  # idempotent: fills may arrive via stream and reconciliation
        self.seen_fill_ids.add(fill.fill_id)
        pos = self.positions.get(fill.market_slug)
        if pos is None or (pos.qty == 0 and pos.side != fill.intent.holding):
            # A flat position may be re-opened on the other side; the ledger keeps the
            # aggregate realized P&L of the closed one.
            pos = Position(
                market_slug=fill.market_slug, match_key=fill.match_key, side=fill.intent.holding
            )
            self.positions[fill.market_slug] = pos
        px = fill.intent.side_price(fill.price)
        if fill.intent.opens:
            self.cash -= px * fill.qty + fill.fee
        else:
            self.cash += px * fill.qty - fill.fee
        self.total_fees += fill.fee
        pnl = pos.apply_fill(fill)
        self.realized_pnl += pnl
        return pnl

    def settle(self, market_slug: str, yes_settlement_price: Decimal) -> Decimal:
        pos = self.positions.get(market_slug)
        if pos is None or pos.qty == 0:
            return ZERO
        payout_per = yes_settlement_price if pos.side == "YES" else ONE - yes_settlement_price
        self.cash += payout_per * pos.qty
        pnl = pos.settle(yes_settlement_price)
        self.realized_pnl += pnl
        self.settled_pnl += pnl
        return pnl

    def open_positions(self) -> list[Position]:
        return [p for p in self.positions.values() if p.qty > 0]

    def match_max_loss(self, match_key: str) -> Decimal:
        """Combined worst-case settlement loss of every open position in one match.

        Positions are *not* netted against each other: a match-winner and a set-winner
        position share one budget conservatively.
        """
        return sum(
            (p.max_settlement_loss for p in self.open_positions() if p.match_key == match_key),
            ZERO,
        )

    def total_max_loss(self) -> Decimal:
        return sum((p.max_settlement_loss for p in self.open_positions()), ZERO)


def opposite(intent: OrderIntent) -> str:
    return "NO" if intent.holding == "YES" else "YES"
